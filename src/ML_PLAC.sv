module cube_root_init(
    input [13:0]x_in,
    output [8:0]y_out
);

    wire [14:0]diff1  = {1'b0, x_in} - {1'b0, 14'b00101001000000};
    wire [14:0]diff2  = {1'b0, x_in} - {1'b0, 14'b00101111101000};
    wire [14:0]diff3  = {1'b0, x_in} - {1'b0, 14'b00111000100110};
    wire [14:0]diff4  = {1'b0, x_in} - {1'b0, 14'b01000100101000};
    wire [14:0]diff5  = {1'b0, x_in} - {1'b0, 14'b01010101111100};
    wire [14:0]diff6  = {1'b0, x_in} - {1'b0, 14'b01011100111111};
    wire [14:0]diff7  = {1'b0, x_in} - {1'b0, 14'b01110000000000};
    wire [14:0]diff8  = {1'b0, x_in} - {1'b0, 14'b01110101010010};
    wire [14:0]diff9  = {1'b0, x_in} - {1'b0, 14'b01111010100011};
    wire [14:0]diff10 = {1'b0, x_in} - {1'b0, 14'b10000011011011};
    wire [14:0]diff11 = {1'b0, x_in} - {1'b0, 14'b10011100001000};
    wire [14:0]diff12 = {1'b0, x_in} - {1'b0, 14'b10100101000100};
    wire [14:0]diff13 = {1'b0, x_in} - {1'b0, 14'b10101100001010};
    wire [14:0]diff14 = {1'b0, x_in} - {1'b0, 14'b10110001010111};
    wire [14:0]diff15 = {1'b0, x_in} - {1'b0, 14'b10111011001111};
    wire [14:0]diff16 = {1'b0, x_in} - {1'b0, 14'b11000111101011};
    wire [14:0]diff17 = {1'b0, x_in} - {1'b0, 14'b11101110111000};
    wire [14:0]diff18 = {1'b0, x_in} - {1'b0, 14'b11111010111100};

    wire s1 = diff1[14];
    wire s2 = diff2[14];
    wire s3 = diff3[14];
    wire s4 = diff4[14];
    wire s5 = diff5[14];
    wire s6 = diff6[14];
    wire s7 = diff7[14];
    wire s8 = diff8[14];
    wire s9 = diff9[14];
    wire s10 = diff10[14];
    wire s11 = diff11[14];
    wire s12 = diff12[14];
    wire s13 = diff13[14];
    wire s14 = diff14[14];
    wire s15 = diff15[14];
    wire s16 = diff16[14];
    wire s17 = diff17[14];
    wire s18 = diff18[14];

    wire [17:0]ss = {s1, s2, s3, s4, s5, s6, s7, s8, s9, s10, s11, s12, s13, s14, s15, s16, s17, s18};
    reg [13:0]bq;

    reg [13:0]term1;
    reg [13:0]term2;
    reg [13:0]term3;

    always @(*) begin
        case(ss)
            18'b111111111111111111: bq = 14'b01010111111110;
            18'b011111111111111111: bq = 14'b01011100110000;
            18'b001111111111111111: bq = 14'b01100010011000;
            18'b000111111111111111: bq = 14'b01101001001101;
            18'b000011111111111111: bq = 14'b01110001101001;
            18'b000001111111111111: bq = 14'b01111100011001;
            18'b000000111111111111: bq = 14'b01111100100000;
            18'b000000011111111111: bq = 14'b01111100001101;
            18'b000000001111111111: bq = 14'b10001010110110;
            18'b000000000111111111: bq = 14'b10001011001000;
            18'b000000000011111111: bq = 14'b10001011001101;
            18'b000000000001111111: bq = 14'b10001010110110;
            18'b000000000000111111: bq = 14'b10001010011011;
            18'b000000000000011111: bq = 14'b10011111111000;
            18'b000000000000001111: bq = 14'b10100000001111;
            18'b000000000000000111: bq = 14'b10100000101000;
            18'b000000000000000011: bq = 14'b10100000110001;
            18'b000000000000000001: bq = 14'b10100000011010;
            18'b000000000000000000: bq = 14'b10100000000111;
            default: bq = 14'b0;
        endcase

        case({s3, s13})
            2'b11: term1 = x_in[13:0];
            2'b01: term1 = {1'b0, x_in[13:1]};
            2'b00: term1 = {2'b0, x_in[13:2]};
            default: term1 = 14'b0;
        endcase

        case({s1, s2, s3, s5, s8, s13})
            6'b111111: term2 = {2'b0, x_in[13:2]};
            6'b011111: term2 = {3'b0, x_in[13:3]};
            6'b001111: term2 = 14'b0;
            6'b000111: term2 = {2'b0, x_in[13:2]};
            6'b000011: term2 = {3'b0, x_in[13:3]};
            6'b000001: term2 = 14'b0;
            6'b000000: term2 = {3'b0, x_in[13:3]};
            default: term2 = 14'b0;
        endcase

        case ({s3, s4})
            2'b01: term3 = {3'b0, x_in[13:3]};
            default: term3 = 14'b0;
        endcase
    end

    wire [14:0]sum1;
    wire [14:0]sum2;
    wire [14:0]y_15bit;

    CLA_15bit u1_CLA_15bit(
        .A     	( {1'b0, term1}  ),
        .B     	( {1'b0, term2}  ),
        .C_in  	( 1'b0           ),
        .S     	( sum1           ),
        .C_out 	(                )       
    );

    CLA_15bit u2_CLA_15bit(
        .A     	( sum1           ),
        .B     	( {1'b0, term3}  ),
        .C_in  	( 1'b0           ),
        .S     	( sum2           ),
        .C_out 	(                )       
    );

    CLA_15bit u3_CLA_15bit(
        .A     	( sum2           ),
        .B     	( {1'b0, bq}     ),
        .C_in  	( 1'b0           ),
        .S     	( y_15bit        ),
        .C_out 	(                )       
    );

    wire [14:0] rounded_sum = y_15bit + 15'd32;
    assign y_out = rounded_sum[14:6];      

endmodule